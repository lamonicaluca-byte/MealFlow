let counter = 0;
function ing(
  name: string,
  quantity: number | null,
  unit: RecipeIngredient["unit"],
  category: RecipeIngredient["category"],
  optional = false,
): RecipeIngredient {
  counter += 1;
  return { id: `ing-${counter.toString().padStart(4, "0")}`, name, quantity, unit, category, optional };
}

